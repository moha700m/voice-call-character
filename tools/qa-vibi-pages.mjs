import { chromium } from 'playwright';
import fs from 'node:fs/promises';

const url='https://moha700m.github.io/voice-call-character/';
const out='artifacts/vibi-pages-qa';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},locale:'ar-SA'});
const consoleErrors=[];
page.on('console',m=>{if(m.type()==='error')consoleErrors.push(m.text())});
await page.goto(url,{waitUntil:'networkidle',timeout:60000});
const title=await page.title();
const body=await page.locator('body').innerText();
const html=await page.content();
if(!body.includes('سايبر × Vibi')) throw new Error('Vibi UI marker missing');
if(!body.includes('Vibi API Key')) throw new Error('API key connect field missing');
if(html.includes('agent_6401m373bj55ft0bnxpf57d7bq36')||html.includes('elevenlabs-convai')) throw new Error('obsolete ElevenLabs Agent integration still present');
await page.locator('#apiKey').fill('sk_invalid_qa_only');
await page.locator('#connect').click();
await page.waitForTimeout(2500);
const msg=await page.locator('#connectMsg').innerText();
await page.screenshot({path:`${out}/mobile.png`,fullPage:true});
await fs.writeFile(`${out}/report.json`,JSON.stringify({url,title,invalidKeyMessage:msg,consoleErrors},null,2));
console.log(JSON.stringify({title,invalidKeyMessage:msg,consoleErrors},null,2));
await browser.close();
